-- Pagination: OFFSET vs keyset on books.
EXPLAIN (ANALYZE, BUFFERS)
SELECT *
FROM books
ORDER BY book_id DESC
LIMIT 10 OFFSET 0;

EXPLAIN (ANALYZE, BUFFERS)
SELECT *
FROM books
ORDER BY book_id DESC
LIMIT 10 OFFSET 49990;

EXPLAIN (ANALYZE, BUFFERS)
SELECT *
FROM books
WHERE book_id < 'fffe2355-0158-4ca8-b045-5ab7e3ef1412'
ORDER BY book_id DESC
LIMIT 10;

EXPLAIN (ANALYZE, BUFFERS)
SELECT *
FROM books
WHERE book_id < '000dd794-7cdd-479a-84ba-c2e144068633'
ORDER BY book_id DESC
LIMIT 10;

EXPLAIN (ANALYZE, BUFFERS)
SELECT *
FROM books
ORDER BY book_id DESC
